#!/usr/bin/env python3
"""Generates src/components/intro/wordmark-paths.ts from the Inter font (SIL OFL).
Run once: python3 scripts/build-wordmark.py <path-to-Inter-SemiBold.otf>
The generated file is committed; nothing parses fonts at runtime."""
import sys
from fontTools.ttLib import TTFont
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen

font_path = sys.argv[1] if len(sys.argv) > 1 else "/usr/share/fonts/opentype/inter/Inter-SemiBold.otf"
text = "BridgeVoice"
font = TTFont(font_path)
gs = font.getGlyphSet()
cmap = font.getBestCmap()
upm = font["head"].unitsPerEm
scale = 100 / upm  # cap height ~ 73 units tall in a 100-unit em
x = 0
glyphs = []
for ch in text:
    name = cmap[ord(ch)]
    g = gs[name]
    pen = SVGPathPen(gs, ntos=lambda v: ("%.2f" % v).rstrip("0").rstrip("."))
    tp = TransformPen(pen, (scale, 0, 0, -scale, x * scale, 0))
    g.draw(tp)
    glyphs.append((ch, pen.getCommands()))
    x += g.width
width = x * scale
asc = 78
desc = 24
out = "// AUTO-GENERATED by scripts/build-wordmark.py from Inter SemiBold (SIL Open Font License). Do not edit.\n"
out += "export const WORDMARK_TEXT = %r;\n" % text
out += "export const WORDMARK_VIEWBOX = \"0 -%d %.1f %d\";\n" % (asc, width, asc + desc)
out += "export const WORDMARK_GLYPHS: string[] = [\n"
for ch, d in glyphs:
    out += "  \"%s\",\n" % d
out += "];\n"
out = out.replace("'BridgeVoice'", '"BridgeVoice"')
open("src/components/intro/wordmark-paths.ts", "w").write(out)
print("ok width", round(width, 1), "glyphs", len(glyphs))
